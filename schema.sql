-- Record each Telegram message and update both counters in one transaction.
-- The unique message key makes retrying the RPC safe after network timeouts.
create or replace function public.record_bot_activity_batch(p_items jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    with inserted as (
        insert into public.bot_activity_events
            (chat_id, user_id, message_id, username, first_name, created_at)
        select
            (item->>'chat_id')::bigint,
            (item->>'user_id')::bigint,
            (item->>'message_id')::bigint,
            nullif(item->>'username', ''),
            coalesce(nullif(item->>'first_name', ''), 'Пользователь'),
            coalesce(nullif(item->>'created_at', '')::timestamptz, now())
        from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) as data(item)
        where nullif(item->>'message_id', '') is not null
        on conflict (chat_id, message_id) do nothing
        returning chat_id, user_id, username, first_name, created_at
    ),
    grouped as (
        select
            chat_id, user_id,
            (created_at at time zone 'Europe/Moscow')::date as day,
            count(*)::bigint as messages,
            max(username) as username,
            coalesce(max(first_name), 'Пользователь') as first_name,
            max(created_at) as last_seen
        from inserted
        group by chat_id, user_id, (created_at at time zone 'Europe/Moscow')::date
    ),
    daily_write as (
        insert into public.bot_activity_daily
            (chat_id, user_id, day, username, first_name, messages, updated_at)
        select chat_id, user_id, day, username, first_name, messages, now()
        from grouped
        on conflict (chat_id, user_id, day)
        do update set
            messages = public.bot_activity_daily.messages + excluded.messages,
            username = coalesce(excluded.username, public.bot_activity_daily.username),
            first_name = coalesce(excluded.first_name, public.bot_activity_daily.first_name),
            updated_at = now()
        returning chat_id, user_id
    )
    insert into public.bot_users
        (user_id, chat_id, username, first_name, warns, rank, messages, last_seen)
    select user_id, chat_id, max(username), coalesce(max(first_name), 'Пользователь'),
           0, 0, sum(messages), max(last_seen)
    from grouped
    group by user_id, chat_id
    on conflict (user_id, chat_id)
    do update set
        username = coalesce(excluded.username, public.bot_users.username),
        first_name = coalesce(excluded.first_name, public.bot_users.first_name),
        messages = public.bot_users.messages + excluded.messages,
        last_seen = greatest(public.bot_users.last_seen, excluded.last_seen);
end;
$$;

revoke all on function public.record_bot_activity_batch(jsonb) from public, anon, authenticated;
grant execute on function public.record_bot_activity_batch(jsonb) to service_role;

create or replace function public.increment_bot_activity_daily_batch(p_items jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    item jsonb;
begin
    for item in select value from jsonb_array_elements(coalesce(p_items, '[]'::jsonb))
    loop
        insert into public.bot_activity_daily
            (chat_id, user_id, day, username, first_name, messages, updated_at)
        values
            ((item->>'chat_id')::bigint,
             (item->>'user_id')::bigint,
             (item->>'day')::date,
             nullif(item->>'username', ''),
             coalesce(nullif(item->>'first_name', ''), 'Пользователь'),
             greatest(0, coalesce((item->>'messages')::bigint, 0)),
             now())
        on conflict (chat_id, user_id, day)
        do update set
            messages = public.bot_activity_daily.messages + excluded.messages,
            username = coalesce(excluded.username, public.bot_activity_daily.username),
            first_name = coalesce(nullif(excluded.first_name, ''), public.bot_activity_daily.first_name),
            updated_at = now();
    end loop;
end;
$$;

revoke all on function public.increment_bot_activity_daily_batch(jsonb) from public, anon, authenticated;
grant execute on function public.increment_bot_activity_daily_batch(jsonb) to service_role;


-- Atomic warning ledger + profile counter. Concurrent warnings for the same target
-- serialize on an advisory transaction lock; audit and profile update commit together.
create or replace function public.pear_issue_warning(
    p_chat_id bigint,
    p_actor_id bigint,
    p_target_id bigint,
    p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_before integer;
    v_count integer;
    v_now timestamptz := now();
begin
    if p_chat_id is null or p_actor_id is null or p_target_id is null or p_target_id = 0 then
        return jsonb_build_object('ok', false, 'reason', 'invalid_request');
    end if;
    perform pg_advisory_xact_lock(hashtext(p_chat_id::text), hashtext(p_target_id::text));
    select count(*)::integer into v_before
    from public.bot_audit
    where chat_id = p_chat_id and target_id = p_target_id
      and action = 'warn' and created_at >= v_now - interval '7 days';
    insert into public.bot_audit(chat_id, actor_id, action, target_id, details, created_at)
    values (p_chat_id, p_actor_id, 'warn', p_target_id,
            left(coalesce(p_reason, ''), 500) || '; expires_in_days=7', v_now);
    v_count := v_before + 1;
    insert into public.bot_users(user_id, chat_id, warns, rank, messages, first_name)
    values (p_target_id, p_chat_id, v_count, 0, 0, 'Пользователь')
    on conflict (user_id, chat_id) do update
      set warns = excluded.warns;
    return jsonb_build_object('ok', true, 'before_count', v_before, 'active_count', v_count);
end;
$$;
