create table if not exists public.bot_users (
    user_id bigint not null,
    chat_id bigint not null,
    username text,
    first_name text not null default 'Пользователь',
    warns integer not null default 0 check (warns >= 0),
    rank integer not null default 0,
    messages bigint not null default 0 check (messages >= 0),
    created_at timestamptz not null default now(),
    last_seen timestamptz,
    primary key (user_id, chat_id)
);

create table if not exists public.bot_audit (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    actor_id bigint not null,
    action text not null,
    target_id bigint,
    details text,
    created_at timestamptz not null default now()
);

create index if not exists bot_audit_chat_created_idx
    on public.bot_audit (chat_id, created_at desc);

create table if not exists public.bot_marriages (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user1_id bigint not null,
    user1_name text not null,
    user2_id bigint not null,
    user2_name text not null,
    status text not null default 'pending'
        check (status in ('pending', 'married', 'divorced')),
    created_at timestamptz not null default now(),
    accepted_at timestamptz,
    check (user1_id <> user2_id)
);

create index if not exists bot_marriages_chat_idx
    on public.bot_marriages (chat_id, status);

-- Per-message activity events power daily/weekly/monthly/yearly leaderboards.
create table if not exists public.bot_activity_events (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user_id bigint not null,
    username text,
    first_name text not null default 'Пользователь',
    created_at timestamptz not null default now()
);

create index if not exists bot_activity_events_chat_created_idx
    on public.bot_activity_events (chat_id, created_at desc);

create index if not exists bot_activity_events_chat_user_created_idx
    on public.bot_activity_events (chat_id, user_id, created_at desc);
