-- Pear CM: complete Supabase schema
-- Paste this entire file into Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Configure the bot with SUPABASE_SERVICE_KEY (service_role key) in secrets.
-- This script is idempotent: safe to run again; it does not delete existing data.

create table if not exists public.bot_users (
    user_id bigint not null,
    chat_id bigint not null,
    username text,
    first_name text not null default 'Пользователь',
    warns integer not null default 0 check (warns >= 0),
    rank integer not null default 0,
    messages bigint not null default 0 check (messages >= 0),
    created_at timestamptz not null default now(),
    last_seen timestamptz,
    primary key (user_id, chat_id)
);

create table if not exists public.bot_audit (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    actor_id bigint not null,
    action text not null,
    target_id bigint,
    details text,
    created_at timestamptz not null default now()
);

create table if not exists public.bot_activity_events (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user_id bigint not null,
    username text,
    first_name text not null default 'Пользователь',
    created_at timestamptz not null default now()
);

create table if not exists public.bot_marriages (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user1_id bigint not null,
    user1_name text not null,
    user2_id bigint not null,
    user2_name text not null,
    status text not null default 'pending'
        check (status in ('pending', 'married', 'divorced')),
    created_at timestamptz not null default now(),
    accepted_at timestamptz,
    check (user1_id <> user2_id)
);

create table if not exists public.bot_chat_settings (
    chat_id bigint primary key,
    settings jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.bot_global_settings (
    key text primary key,
    value text,
    updated_at timestamptz not null default now()
);

create table if not exists public.bot_operators (
    user_id bigint primary key,
    active boolean not null default true,
    created_by bigint,
    created_at timestamptz not null default now()
);

create table if not exists public.bot_global_bans (
    user_id bigint primary key,
    active boolean not null default true,
    reason text not null default '',
    actor_id bigint,
    created_at timestamptz not null default now()
);

-- Reports supports both the current report/appeal commands and suggestions.
create table if not exists public.bot_reports (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user_id bigint,
    reporter_id bigint,
    target_id bigint,
    message_id bigint,
    body text,
    details text,
    status text not null default 'open',
    closed_by bigint,
    closed_reason text,
    created_at timestamptz not null default now(),
    closed_at timestamptz
);

create table if not exists public.bot_appeals (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    user_id bigint not null,
    body text not null,
    status text not null default 'open',
    closed_by bigint,
    closed_reason text,
    created_at timestamptz not null default now(),
    closed_at timestamptz
);

create table if not exists public.bot_notes (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    content text not null,
    created_at timestamptz not null default now()
);

-- Compatibility table for any bug-report flow that uses singular "bug_report".
-- It is separate from bot_reports and won't interfere with existing report data.
create table if not exists public.bug_report (
    id bigint generated by default as identity primary key,
    user_id bigint,
    chat_id bigint,
    username text,
    title text,
    description text,
    body text,
    details text,
    status text not null default 'open',
    created_at timestamptz not null default now(),
    updated_at timestamptz,
    resolved_at timestamptz,
    metadata jsonb not null default '{}'::jsonb
);

