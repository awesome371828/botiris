alter table public.bot_reports add column if not exists message_id bigint;
alter table public.bot_reports add column if not exists body text;
alter table public.bot_reports add column if not exists details text;
alter table public.bot_reports add column if not exists status text not null default 'open';
alter table public.bot_reports add column if not exists closed_by bigint;
alter table public.bot_reports add column if not exists closed_reason text;
alter table public.bot_reports add column if not exists created_at timestamptz not null default now();
alter table public.bot_reports add column if not exists closed_at timestamptz;

alter table public.bot_appeals add column if not exists body text;
alter table public.bot_appeals add column if not exists status text not null default 'open';
alter table public.bot_appeals add column if not exists closed_by bigint;
alter table public.bot_appeals add column if not exists closed_reason text;
alter table public.bot_appeals add column if not exists created_at timestamptz not null default now();
alter table public.bot_appeals add column if not exists closed_at timestamptz;

create index if not exists bot_audit_chat_created_idx
    on public.bot_audit (chat_id, created_at desc);
create index if not exists bot_audit_created_idx
    on public.bot_audit (created_at desc);
create index if not exists bot_activity_events_chat_created_idx
    on public.bot_activity_events (chat_id, created_at desc);
create index if not exists bot_activity_events_chat_user_created_idx
    on public.bot_activity_events (chat_id, user_id, created_at desc);
create index if not exists bot_activity_events_created_idx
    on public.bot_activity_events (created_at desc);
create index if not exists bot_marriages_chat_idx
    on public.bot_marriages (chat_id, status);
create index if not exists bot_reports_chat_status_created_idx
    on public.bot_reports (chat_id, status, created_at desc);
create index if not exists bot_appeals_chat_status_created_idx
    on public.bot_appeals (chat_id, status, created_at desc);
create index if not exists bot_notes_user_created_idx
    on public.bot_notes (user_id, created_at desc);
create index if not exists bug_report_status_created_idx
    on public.bug_report (status, created_at desc);
create index if not exists bug_report_user_created_idx
    on public.bug_report (user_id, created_at desc);

-- The bot uses the service_role key server-side. Keep the database inaccessible
-- to anon/authenticated clients; never put the service key in the Mini App/browser.
alter table public.bot_users enable row level security;
alter table public.bot_audit enable row level security;
alter table public.bot_activity_events enable row level security;
alter table public.bot_marriages enable row level security;
alter table public.bot_chat_settings enable row level security;
alter table public.bot_global_settings enable row level security;
alter table public.bot_operators enable row level security;
alter table public.bot_global_bans enable row level security;
alter table public.bot_reports enable row level security;
alter table public.bot_appeals enable row level security;
alter table public.bot_notes enable row level security;
alter table public.bug_report enable row level security;

revoke all on public.bot_users, public.bot_audit, public.bot_activity_events,
    public.bot_marriages, public.bot_chat_settings, public.bot_global_settings,
    public.bot_operators, public.bot_global_bans, public.bot_reports,
    public.bot_appeals, public.bot_notes, public.bug_report from anon, authenticated;

grant all on public.bot_users, public.bot_audit, public.bot_activity_events,
    public.bot_marriages, public.bot_chat_settings, public.bot_global_settings,
    public.bot_operators, public.bot_global_bans, public.bot_reports,
    public.bot_appeals, public.bot_notes, public.bug_report to service_role;
grant usage, select on all sequences in schema public to service_role;
